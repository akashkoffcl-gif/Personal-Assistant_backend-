import { IsString, IsNotEmpty, IsOptional, IsArray, IsBoolean } from 'class-validator';

export class InitiateDevicePairingDto {
  @IsString()
  @IsNotEmpty()
  deviceName: string;

  @IsString()
  @IsNotEmpty()
  deviceModel: string;

  @IsString()
  @IsNotEmpty()
  osVersion: string;

  @IsString()
  @IsNotEmpty()
  appVersion: string;

  @IsString()
  @IsNotEmpty()
  publicKey: string; // Base64 or PEM encoded public key generated in Android Keystore
}

export class ConfirmDevicePairingDto {
  @IsString()
  @IsNotEmpty()
  deviceId: string;

  @IsString()
  @IsNotEmpty()
  signedChallenge: string; // Signature of the pairing challenge generated by device private key
}

export class RegisterFcmTokenDto {
  @IsString()
  @IsNotEmpty()
  deviceId: string;

  @IsString()
  @IsNotEmpty()
  fcmToken: string;
}

export class UpdatePermissionsDto {
  @IsString()
  @IsNotEmpty()
  deviceId: string;

  @IsArray()
  permissions: {
    permissionKey: string;
    isGranted: boolean;
  }[];
}

export class IngestMobileEventDto {
  @IsString()
  @IsNotEmpty()
  deviceId: string;

  @IsString()
  @IsNotEmpty()
  sourceApp: string;

  @IsOptional()
  @IsString()
  appName?: string;

  @IsString()
  @IsNotEmpty()
  category: string; // COMMUNICATION, CALENDAR, SYSTEM, ALERT

  @IsOptional()
  @IsString()
  title?: string;

  @IsOptional()
  @IsString()
  summary?: string;

  @IsOptional()
  rawMetadata?: Record<string, any>;

  @IsString()
  @IsNotEmpty()
  occurredAt: string; // ISO string
}

export class ExecuteMobileCommandDto {
  @IsString()
  @IsNotEmpty()
  deviceId: string;

  @IsString()
  @IsNotEmpty()
  commandType: string;

  @IsNotEmpty()
  payload: Record<string, any>;

  @IsOptional()
  @IsBoolean()
  requiresConfirmation?: boolean;
}

export class RespondMobileCommandDto {
  @IsString()
  @IsNotEmpty()
  commandId: string;

  @IsString()
  @IsNotEmpty()
  status: 'APPROVED' | 'REJECTED' | 'EXECUTED' | 'FAILED';

  @IsOptional()
  @IsString()
  failureReason?: string;
}

